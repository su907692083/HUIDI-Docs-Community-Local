const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),pub=path.join(root,'public');
const read=f=>fs.readFileSync(path.join(pub,f),'utf8');
const html=read('editor.html'),js=read('huidi-layout-policy-rc1610.js'),css=read('huidi-layout-policy-rc1610.css');
const table=read('flypigbox-editor-table-output.js'),unified=read('flypigbox-editor-unified.js'),quick=read('flypigbox-quotation-quick-flow.js');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'RELEASE-MANIFEST.json'),'utf8'));
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const errors=[];const ok=(c,m)=>{if(!c)errors.push(m)};
ok(pkg.version==='1.2.0-rc16.10','package version is not RC16.10');
ok(manifest.version==='1.2.0-RC16.10'&&manifest.release==='RC16.10','release manifest is not RC16.10');
ok(html.includes('huidi-layout-policy-rc1610.css'),'editor missing RC16.10 css');
ok(html.includes('huidi-layout-policy-rc1610.js'),'editor missing RC16.10 js');
ok(!html.includes('<link rel="stylesheet" href="./huidi-layout-policy-rc169.css'),'RC16.9 layout css still active');
ok(!html.includes('<script src="./huidi-layout-policy-rc169.js'),'RC16.9 layout js still active');
ok(!html.includes('<script src="./huidi-page-fit-workspace-rc1665.js'),'RC16.6.5 controller is still active');
['quotation','proforma_invoice','sales_contract','commercial_invoice','packing_list'].forEach(t=>ok(js.includes(`'${t}'`),`missing supported type ${t}`));
ok(js.includes("KEY_PREFIX='huidi_document_density_v1:'"),'density storage missing');
ok(js.includes('data-huidi-density="compact"')&&js.includes('>紧凑</button>'),'compact button missing');
ok(js.includes('data-huidi-density="standard"')&&js.includes('>标准</button>'),'standard button missing');
ok(!js.includes('>优先一页</button>'),'prefer-one-page button is still visible');
ok(!js.includes('<span>内容适配</span>'),'content-fit label is still visible');
ok(!js.includes('huidiPageFitStatus'),'layout status text still consumes toolbar space');
ok(js.includes("p.classList.toggle('huidi-document-compact'"),'shared compact class missing');
ok(js.includes("p.classList.remove('huidi-document-one-page')"),'legacy one-page class is not cleared');
ok(js.includes("p.dataset.huidiPageFit='standard'"),'legacy force-one-page marker not neutralized');
ok(js.includes('HUIDI:layout-policy-changed'),'layout policy event missing');
const pageRule=(css.match(/#piPaper\.huidi-document-compact \.pdf-page\{([^}]*)\}/)||[])[1]||'';
ok(!/(?:^|;)\s*(?:width|height|padding)\s*:/i.test(pageRule),'compact css overrides physical PDF page geometry');
ok(css.includes('object-fit:contain'),'compact product images do not preserve aspect ratio');
ok(unified.includes("window.HUIDILayoutPolicy?.version==='1.2.0-RC16.10'"),'single pagination authority not retained');
ok(quick.includes("policy?.version==='1.2.0-RC16.10'"),'quotation helper does not defer to RC16.10');
ok(table.includes("function preferCompact(){return currentLayoutPolicy()==='compact';}"),'workbook compact policy missing');
ok(table.includes("preferCompact()?'huidi-layout-compact':''"),'workbook compact class missing');
ok(table.includes('const fitHeight=0;'),'XLSX still tries to force compact sheets to one page');
if(errors.length){console.error('RC16.10 compact/standard layout validation FAIL');errors.forEach(e=>console.error(' - '+e));process.exit(1)}
console.log('RC16.10 compact/standard layout validation PASS');
