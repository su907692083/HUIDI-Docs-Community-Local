const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),pub=path.join(root,'public');
const read=f=>fs.readFileSync(path.join(pub,f),'utf8');
const html=read('editor.html'),js=read('huidi-layout-policy-rc169.js'),css=read('huidi-layout-policy-rc169.css');
const table=read('flypigbox-editor-table-output.js'),unified=read('flypigbox-editor-unified.js'),quick=read('flypigbox-quotation-quick-flow.js');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'RELEASE-MANIFEST.json'),'utf8'));
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const errors=[];const ok=(c,m)=>{if(!c)errors.push(m)};
ok(pkg.version==='1.2.0-rc16.9','package version is not RC16.9');
ok(manifest.version==='1.2.0-RC16.9'&&manifest.release==='RC16.9','release manifest is not RC16.9');
ok(html.includes('huidi-layout-policy-rc169.css'),'editor missing RC16.9 css');
ok(html.includes('huidi-layout-policy-rc169.js'),'editor missing RC16.9 js');
ok(!html.includes('<link rel="stylesheet" href="./huidi-layout-policy-rc168.css'),'RC16.8 layout css still active');
ok(!html.includes('<script src="./huidi-layout-policy-rc168.js'),'RC16.8 layout js still active');
ok(!html.includes('<script src="./huidi-page-fit-workspace-rc1665.js'),'RC16.6.5 quotation-only controller is still active');
['quotation','proforma_invoice','sales_contract','commercial_invoice','packing_list'].forEach(t=>ok(js.includes(`'${t}'`),`missing supported type ${t}`));
ok(js.includes("KEY_PREFIX='huidi_document_page_fit_v2:'"),'per-document layout storage missing');
ok(js.includes('scheduleSingleRender'),'single render scheduler missing');
ok(js.includes("document.body.dataset.huidiStablePagination='1'"),'stable pagination marker missing');
ok(!js.includes('box.hidden=!quotation'),'quotation-only visibility gate still present');
ok(!js.includes("type()==='quotation'&&enabled()"),'quotation-only state gate still present');
ok(js.includes('huidi-document-one-page'),'shared compact class missing');
ok(js.includes('HUIDI:layout-policy-changed'),'shared layout policy event missing');
const pageRule=(css.match(/#piPaper\.huidi-document-one-page \.pdf-page\{([^}]*)\}/)||[])[1]||'';
ok(!/(?:^|;)\s*(?:width|height|padding)\s*:/i.test(pageRule),'compact css overrides physical PDF page geometry');
ok(html.includes("const directTable=chunk.matches?.('table')?chunk:chunk.querySelector?.(':scope > table')"),'nested table safe-split guard missing');
ok(html.includes('linearizeOversizedNestedLayouts'),'nested showcase multipage fallback missing');
ok(html.includes('normalizeProductSummaryOrder'),'product-summary ordering closure missing');
ok(html.includes(".pdf-total-card,.money-table"),'product total tail selector is incomplete');
ok(unified.includes("window.HUIDILayoutPolicy?.version==='1.2.0-RC16.9'"),'legacy post-pagination authority is not disabled under RC16.9');
ok(quick.includes("policy?.version==='1.2.0-RC16.9'"),'quotation helper does not defer to RC16.9 policy');
ok(table.includes('pageFit:currentLayoutPolicy()'),'workbook render signature does not include layout policy');
ok(table.includes("'HUIDI:layout-policy-changed'"),'workbook does not listen to layout policy change');
ok(table.includes("preferOnePage()?'huidi-layout-one-page':''"),'workbook preview compact class missing');
ok(table.includes('(sheet.rows?.length||0)<=48?1:0'),'bounded XLSX fit-to-height rule missing');
if(errors.length){console.error('RC16.9 pagination/layout validation FAIL');errors.forEach(e=>console.error(' - '+e));process.exit(1)}
console.log('RC16.9 pagination/layout validation PASS');
